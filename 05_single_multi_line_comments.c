 // Topic: Demonstrate Single-Line and Multi-Line Comments
#include <stdio.h>

int main()
{
    // This is a single-line comment.

    /*
       This is a multi-line comment.
       It can extend across multiple lines.
    */

    int a = 10, b = 20;

    printf("First number = %d\n", a);
    printf("Second number = %d\n", b);
    printf("Sum = %d\n", a + b);

    return 0;
}
